#!/usr/bin/env python3
"""Enable the PixelLab art set ONLY after all 36 PNG images pass checks.

Old 7-tier save indices deliberately unchanged.
This operation replaces only the art manifest and updates browser cache keys.
It never exposes API keys or spends generations.
"""
from pathlib import Path
from PIL import Image
from pixellab_plan import assets, ORDER, BY_NAME, UI_NAMES
import json

ROOT=Path(__file__).resolve().parents[1]
DIR=ROOT/"assets"/"pixellab"
for a in assets:
    p=DIR/(a.name+".png")
    if not p.is_file():
        raise SystemExit("Missing PixelLab asset: "+a.name)
    with Image.open(p) as image:
        if image.size!=a.size:
            raise SystemExit(f"Invalid size for {a.name}: {image.size} expected {a.size}")
        if image.mode not in ("RGBA","RGB","P"):
            raise SystemExit("Unsupported color image mode: "+a.name)
        if not a.ui:
            alpha=image.convert("RGBA").getchannel("A")
            lo,hi=alpha.getextrema()
            if lo==hi:
                raise SystemExit("Instrument missing transparency: "+a.name)
    if p.stat().st_size<450:
        raise SystemExit("Suspiciously tiny art file: "+a.name)

assert len(ORDER)==24 and len(UI_NAMES)==12
manifest = [
    {"id": name,"family":BY_NAME[name].family,"level":BY_NAME[name].level,
     "w":BY_NAME[name].w,"h":BY_NAME[name].h,"file":f"assets/pixellab/{name}.png"}
    for name in ORDER
]
idx={(x["family"],x["level"]):i for i,x in enumerate(manifest)}
nexts={i:idx[(x["family"],x["level"]+1)] for i,x in enumerate(manifest)
       if (x["family"],x["level"]+1) in idx}
ui={name:f"assets/pixellab/{name}.png" for name in UI_NAMES}
rev="pixellab-v1-24-levels"
src = """/* Generated by tools/activate_pixellab.py: 24 unique PixelLab-made instruments. */
(()=>{'use strict';
 const approved=__DATA__;
 const uiAssets=__UI__;
 const upgrades=__NEXT__;
 const src=i=>approved[i]?.file||approved[0].file;
 const spans=i=>approved[i]?{w:approved[i].w,h:approved[i].h}:{w:1,h:1};
 const nextTier=i=>Number.isInteger(upgrades[i])?upgrades[i]:null;
 const spawnTiers=[0,0,0,2,2,3,3,5,5];
 window.GridMusicArt={src,spans,nextTier,spawnTiers,approved,uiAssets,total:approved.length,style:'pixellab-game-assets'};
})();
"""
src=(src.replace("__DATA__",json.dumps(manifest,ensure_ascii=False,indent=1))
        .replace("__UI__",json.dumps(ui,indent=1))
        .replace("__NEXT__",json.dumps(nexts,separators=(',',':'))))
(ROOT/"art.js").write_text(src,encoding="utf-8")

game_path=ROOT/"game.js"
game=game_path.read_text(encoding="utf-8")
import re
game=re.sub(r"const ASSET_BUILD='[^']+';",
            "const ASSET_BUILD='"+rev+"';",game,count=1)
game_path.write_text(game,encoding="utf-8")

html_path=ROOT/"index.html"
html=html_path.read_text(encoding="utf-8")
html=re.sub(r'(src="(?:art|game)\.js)(?:\?[^"]*)?(")',
            lambda m:m.group(1)+"?rev="+rev+m.group(2),html)
html_path.write_text(html,encoding="utf-8")
(DIR/"manifest.json").write_text(json.dumps({
    "style":"pixellab-game-assets","generation_cap":40,
    "planned_calls":36,"reserved_for_corrections":4,
    "instruments":manifest,"ui_assets":ui,"next_tier":nexts,
},indent=2),encoding="utf-8")
print(f"Enabled {len(manifest)} instrument levels, {len(ui)} UI assets; no API calls.")
