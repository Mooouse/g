// Android packaging. `gp build <id> --target android` generates games/<id>/android from template/ (the
// proven Android project of "Pop the balloon!": full screen, cutout, Back, no AD_ID, signing from env)
// with the game's appId, name, colors, AdMob App ID and version, adds the theme's icon and splash,
// then `cap sync` copies the web build in. Gradle runs in CI (.github/workflows/android.yml).

import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { ResolvedGame } from '@gp/spec';

const HERE = dirname(dirname(fileURLToPath(import.meta.url)));
const TEMPLATE = join(HERE, 'template');
const THEME_ASSETS = join(HERE, 'theme-assets');
const TEXT = /\.(gradle|xml|java|properties|pro|json|txt)$|gradlew$|\.gitignore$/;

const xml = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/'/g, "\\'").replace(/"/g, '\\"');

function walk(dir: string, out: string[] = []): string[] {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

export interface GenerateOptions {
  game: ResolvedGame;
  /** games/<id> */
  gameDir: string;
  /** Page/splash background color of the theme */
  background: string;
}

/** Themes that ship an Android icon and splash set */
export function themesWithAndroidAssets(): string[] {
  return existsSync(THEME_ASSETS) ? readdirSync(THEME_ASSETS) : [];
}

/** Writes games/<id>/android and games/<id>/capacitor.config.json. Returns the android folder. */
export function generateAndroidProject({ game, gameDir, background }: GenerateOptions): string {
  const out = join(gameDir, 'android');
  // Keep Gradle's caches between builds, regenerate everything else
  for (const e of existsSync(out) ? readdirSync(out) : []) if (e !== '.gradle' && e !== 'build') rmSync(join(out, e), { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  cpSync(TEMPLATE, out, { recursive: true });
  if (!game.theme) throw new Error('Android packaging needs a theme (its icon and splash set); kit code games are web-only');
  const assets = join(THEME_ASSETS, game.theme);
  if (!existsSync(assets)) throw new Error(`theme "${game.theme}" has no Android icon/splash set (packages/android/theme-assets/${game.theme})`);
  cpSync(assets, out, { recursive: true });

  const vars: Record<string, string> = {
    '{{APP_ID}}': game.appId,
    '{{APP_NAME}}': xml(game.title),
    '{{BG_COLOR}}': background.toUpperCase(),
    '{{ADMOB_APP_ID}}': game.android.admobAppId ?? '',
    '{{VERSION_CODE}}': String(game.version.code),
    '{{VERSION_NAME}}': game.version.name,
  };
  for (const f of walk(out)) {
    if (!TEXT.test(f) || f.includes(`${join(out, '.gradle')}`)) continue;
    let s = readFileSync(f, 'utf8');
    if (!s.includes('{{')) continue;
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(k, v);
    writeFileSync(f, s);
  }
  // Java package folder
  const javaRoot = join(out, 'app/src/main/java');
  const pkgDir = join(javaRoot, ...game.appId.split('.'));
  mkdirSync(pkgDir, { recursive: true });
  renameSync(join(javaRoot, '__PACKAGE__', 'MainActivity.java'), join(pkgDir, 'MainActivity.java'));
  rmSync(join(javaRoot, '__PACKAGE__'), { recursive: true, force: true });
  // Without AdMob the App ID meta-data must not be there (the SDK would still start)
  if (!game.android.admobAppId) {
    const m = join(out, 'app/src/main/AndroidManifest.xml');
    writeFileSync(m, readFileSync(m, 'utf8').replace(/\s*<!-- AdMob App ID[\s\S]*?OPTIMIZE_AD_LOADING" android:value="true" \/>/, ''));
  }

  // The Capacitor CLI finds native plugins through the app's package.json: list the runtime's plugins
  const core = JSON.parse(readFileSync(join(HERE, '../core/package.json'), 'utf8')) as { dependencies: Record<string, string> };
  const own = JSON.parse(readFileSync(join(HERE, 'package.json'), 'utf8')) as { dependencies: Record<string, string> };
  writeFileSync(
    join(gameDir, 'package.json'),
    JSON.stringify(
      { name: `gp-game-${game.id}`, private: true, description: 'Generated by gp build --target android — do not edit', dependencies: { ...core.dependencies, '@capacitor/android': own.dependencies['@capacitor/android'] } },
      null,
      2,
    ) + '\n',
  );
  writeFileSync(
    join(gameDir, 'capacitor.config.json'),
    JSON.stringify(
      {
        appId: game.appId,
        appName: game.title,
        webDir: 'dist',
        backgroundColor: background,
        android: { path: 'android', allowMixedContent: false },
        plugins: { SystemBars: { hidden: true, insetsHandling: 'css', initialViewportFitValueHint: 'cover' } },
      },
      null,
      2,
    ) + '\n',
  );
  return out;
}

export interface ManifestCheck {
  permissions: string[];
  forbidden: string[];
  targetSdk: number | null;
  problems: string[];
}

/**
 * Merged-manifest check against the channel's allowlist: every permission must be on it
 * (an allowlist, not a denylist — a new SDK can't slip in ACCESS_WIFI_STATE or AD_ID unnoticed).
 */
export function checkManifest(mergedXml: string, allow: readonly string[], appId: string, minTargetSdk: number): ManifestCheck {
  const permissions = [...new Set([...mergedXml.matchAll(/<uses-permission[^>]*android:name="([^"]+)"/g)].map((m) => m[1]))].sort();
  const allowed = new Set(allow.map((p) => p.replace('${appId}', appId)));
  const forbidden = permissions.filter((p) => !allowed.has(p));
  const t = /android:targetSdkVersion="(\d+)"/.exec(mergedXml);
  const targetSdk = t ? Number(t[1]) : null;
  const problems: string[] = [];
  if (forbidden.length) problems.push(`permissions not allowed by the channel: ${forbidden.join(', ')}`);
  if (targetSdk !== null && targetSdk < minTargetSdk) problems.push(`targetSdkVersion ${targetSdk} < ${minTargetSdk} (Google Play requirement)`);
  return { permissions, forbidden, targetSdk, problems };
}
